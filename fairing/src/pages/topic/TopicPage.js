import React, {Component} from 'react';
import MenuBar from "../../components/MenuBar";
import Heading from "./segments/Heading";
import {PropTypes} from "prop-types";
import ContentView from "./segments/ContentView";

class TopicPage extends Component {

    /**
     * This component is for the conversation around specific topics.
     * Therefore the url must provide the tag
     * @type {{match: *}}
     */
    static propTypes = {
        match: PropTypes.shape({
            params: PropTypes.shape({
                tag: PropTypes.string.isRequired
            })
        }),
    };

    /**
     * This component is for the conversation around specific topics.
     * It should be possible to directly add statement or to react to certain positions or reactions.
     * @param props
     */
    constructor(props) {
        super(props);
        this.state = {
            tag: this.props.match.params.tag,
            menuHeight: 65 // the magic number given by size='large' in MenuBar (generated by semantic ui)
        }
    }

    /**
     * This component shows everything about an topic
     * @returns {JSX.Element}
     */
    render() {
        return (
            <div>
                <MenuBar/>
                <Heading tag={this.state.tag}/>
                <ContentView/>
            </div>
        );
    }
}

export default TopicPage;